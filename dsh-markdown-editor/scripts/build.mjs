const { build } = await import(process.env.DSH_ESBUILD_MODULE || 'esbuild')
import { readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../', import.meta.url))
const verify = process.argv.includes('--check')
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/client.js'], bundle: true, format: 'iife', platform: 'browser',
  target: 'chrome120', outfile: 'lib/client.js', write: !verify, charset: 'utf8',
  legalComments: 'none', banner: { js: '// Generated by npm run build. Edit src/, not this file.' },
})
if (verify && result.outputFiles[0].text !== await readFile(new URL('../lib/client.js', import.meta.url), 'utf8')) {
  throw new Error('lib/client.js is stale; run npm run build')
}

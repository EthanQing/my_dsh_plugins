import { build } from 'esbuild'
import { readFile } from 'node:fs/promises'
const verify = process.argv.includes('--check')
const result = await build({
  entryPoints: ['src/client.js'], bundle: true, format: 'iife', platform: 'browser',
  target: 'chrome120', outfile: 'lib/client.js', write: !verify, charset: 'utf8',
  legalComments: 'none', banner: { js: '// Generated by npm run build. Edit src/, not this file.' },
})
if (verify && result.outputFiles[0].text !== await readFile('lib/client.js', 'utf8')) {
  throw new Error('lib/client.js is stale; run npm run build')
}

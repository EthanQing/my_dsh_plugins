import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises'
import { spawnSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
// Normally resolve this plugin's own devDependency. An explicit module URL also
// permits reusing an already installed build tool without installing anything.
const { build } = await import(process.env.DSH_ESBUILD_MODULE || 'esbuild')
const check = process.argv.includes('--check')
await mkdir(path.join(root, 'lib'), { recursive: true })
const result = await build({
  absWorkingDir: root, entryPoints: ['src/client.js'], bundle: true, format: 'iife',
  platform: 'browser', target: 'chrome120', outfile: 'lib/client.js', write: false,
  charset: 'utf8', legalComments: 'none',
  banner: { js: '// Generated by npm run build; edit src/.' },
})
const host = await readFile(path.join(root, 'src/index.js'), 'utf8')
for (const [name, text] of [['client.js', result.outputFiles[0].text], ['index.js', host]]) {
  const target = path.join(root, 'lib', name)
  if (check) {
    const actual = (await readFile(target, 'utf8')).replace(/\r\n/g, '\n')
    if (actual !== text.replace(/\r\n/g, '\n')) throw new Error(`${name} is stale; run npm run build`)
  } else await writeFile(target, text)
}
for (const file of await readdir(path.join(root, 'lib'))) {
  const checked = spawnSync(process.execPath, ['--check', path.join(root, 'lib', file)], { encoding: 'utf8' })
  if (checked.status !== 0) throw new Error(checked.stderr)
}
for (const locale of ['zh', 'en']) {
  const data = JSON.parse(await readFile(path.join(root, 'locale', `${locale}.json`), 'utf8'))
  if (!data.meta?.title || !data.meta?.description) throw new Error('Missing display metadata')
}
console.log(check ? 'Sources and runtime artifacts match.' : 'Built Host and browser artifacts.')
